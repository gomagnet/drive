CREATE TABLE IF NOT EXISTS users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, email VARCHAR(254) NOT NULL UNIQUE,
 name VARCHAR(160) NOT NULL, avatar TEXT NOT NULL, password_hash VARCHAR(255) NOT NULL DEFAULT '',
 is_admin BOOLEAN NOT NULL DEFAULT FALSE, deleted_at DATETIME(6) NULL, theme VARCHAR(8) NOT NULL DEFAULT 'auto', language VARCHAR(8) NOT NULL DEFAULT 'auto',
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS identities (
 issuer VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL, subject VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL, user_id BIGINT NOT NULL,
 PRIMARY KEY(issuer,subject), FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS spaces (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(160) NOT NULL, owner_id BIGINT NOT NULL,
 personal BOOLEAN NOT NULL DEFAULT FALSE, quota_bytes BIGINT NOT NULL,
 FOREIGN KEY(owner_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS members (
 space_id BIGINT NOT NULL, user_id BIGINT NOT NULL, role VARCHAR(16) NOT NULL,
 PRIMARY KEY(space_id,user_id), FOREIGN KEY(space_id) REFERENCES spaces(id), FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS entries (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, space_id BIGINT NOT NULL, parent_id BIGINT NULL,
 name VARCHAR(255) NOT NULL, folder BOOLEAN NOT NULL DEFAULT FALSE,
 current_version BIGINT NULL, created_by BIGINT NOT NULL, edited_by BIGINT NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), deleted_at DATETIME(6) NULL,
 INDEX listing(space_id,parent_id,deleted_at), FOREIGN KEY(space_id) REFERENCES spaces(id),
 FOREIGN KEY(parent_id) REFERENCES entries(id), FOREIGN KEY(created_by) REFERENCES users(id), FOREIGN KEY(edited_by) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS versions (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, entry_id BIGINT NOT NULL, blob_key CHAR(64) NOT NULL,
 size BIGINT NOT NULL, mime VARCHAR(255) NOT NULL, created_by BIGINT NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 INDEX history(entry_id,id), FOREIGN KEY(entry_id) REFERENCES entries(id), FOREIGN KEY(created_by) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sessions (
 token_hash CHAR(64) PRIMARY KEY, user_id BIGINT NOT NULL, expires_at DATETIME(6) NOT NULL,
 INDEX expiration(expires_at), FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS login_states (
 token_hash CHAR(64) PRIMARY KEY, nonce VARCHAR(128) NOT NULL, verifier VARCHAR(128) NOT NULL,
 expires_at DATETIME(6) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS shares (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, token_hash CHAR(64) NOT NULL UNIQUE, entry_id BIGINT NOT NULL,
 created_by BIGINT NOT NULL, expires_at DATETIME(6) NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(entry_id) REFERENCES entries(id), FOREIGN KEY(created_by) REFERENCES users(id)
) ENGINE=InnoDB;
